// ── Study Blocks ──────────────────────────────────────────────────────────────

export async function getStudyBlocks(token: string): Promise<StudyBlock[]> {
  const rows = await apiFetch('/study-blocks', token);
  return rows.map(toBlock);
}

export async function createStudyBlock(token: string, b: Omit<StudyBlock, 'id'>): Promise<StudyBlock> {
  const row = await apiFetch('/study-blocks', token, {
    method: 'POST',
    body: JSON.stringify({
      course_id: b.courseId, assignment_id: b.assignmentId || null, date: b.date,
      duration: b.duration, is_completed: b.isCompleted, is_auto_generated: b.isAutoGenerated,
    }),
  });
  return toBlock(row);
}

export async function bulkReplaceAutoBlocks(token: string, blocks: StudyBlock[]): Promise<StudyBlock[]> {
  const rows = await apiFetch('/study-blocks/bulk', token, {
    method: 'POST',
    body: JSON.stringify(blocks.map(b => ({
      course_id: b.courseId, assignment_id: b.assignmentId || null, date: b.date,
      duration: b.duration, is_completed: b.isCompleted, is_auto_generated: b.isAutoGenerated,
    }))),
  });
  return rows.map(toBlock);
}

export async function toggleStudyBlock(token: string, id: string): Promise<StudyBlock> {
  const row = await apiFetch(`/study-blocks/${id}/toggle`, token, { method: 'PATCH' });
  return toBlock(row);
}

export async function deleteStudyBlock(token: string, id: string): Promise<void> {
  await apiFetch(`/study-blocks/${id}`, token, { method: 'DELETE' });
}
